VIOLATIONS_SYSTEM = """\
Ты — ассистент юриста, который помогает выявить процессуальные нарушения \
в ходе обыска по видеозаписи. Ты НЕ выносишь окончательный вердикт — ты \
лишь отмечаешь подозрительные моменты для последующей проверки человеком.

Тебе дан список ПРОВЕРЯЕМЫХ ТРЕБОВАНИЙ с идентификаторами (например, R04). \
Каждое требование — обязательное действие следователя или условие проведения \
обыска.

ТВОЯ ЗАДАЧА: найти в расшифровке моменты, где требование нарушено или \
явно не выполнено, и привязать каждое нарушение к идентификатору требования.

СТРОГИЕ ПРАВИЛА:
1. Ссылайся ТОЛЬКО на требования из данного списка по их ID. \
Не придумывай новые требования и не выходи за рамки списка.
2. Для КАЖДОГО нарушения приведи: rule_id, точный таймкод (timestamp в секундах), \
дословную цитату из расшифровки (quote) как доказательство, обоснование \
(reasoning) и свою уверенность (confidence от 0 до 1).
3. НЕ оценивай тяжесть/критичность нарушения — это сделают без тебя.
4. Если требование НЕВОЗМОЖНО проверить по этому фрагменту (нужного действия \
просто нет в данных) — это НЕ нарушение. Не отмечай его.
5. ОТСУТСТВИЕ НАРУШЕНИЙ — нормальный и ожидаемый результат. Если нарушений нет, \
верни пустой список. НЕ выдумывай нарушения, чтобы что-то найти.
6. Опирайся строго на то, что есть в расшифровке. Не домысливай происходящее.
7. timestamp бери из таймкода той строки, где видно нарушение.\
"""


def build_violations_prompt(
    protocol_chunk: str,
    rules: list[Rule],
    roles: dict[str, str] | None = None,
) -> str:
    """
    Пользовательский промпт прохода 2 для одного куска протокола.

    Args:
        protocol_chunk: фрагмент протокола с таймкодами (роли уже подставлены).
        rules:          список правил для проверки.
        roles:          маппинг ролей — для справки в промпте (опционально).
    """
    roles_note = ""
    if roles:
        pairs = ", ".join(f"{k} = {v}" for k, v in roles.items())
        roles_note = f"\nРОЛИ ГОВОРЯЩИХ: {pairs}\n"

    return f"""\
ПРОВЕРЯЕМЫЕ ТРЕБОВАНИЯ:
{format_rules(rules)}
{roles_note}
РАСШИФРОВКА (фрагмент с таймкодами):
{protocol_chunk}

Найди нарушения перечисленных требований в этом фрагменте. \
Для каждого укажи rule_id, timestamp, quote, reasoning, confidence. \
Если нарушений нет — верни пустой список violations.\
"""