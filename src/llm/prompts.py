# ---------------------------------------------------------------------------

SPEAKER_ROLES_SYSTEM = """\
Ты — ассистент-аналитик, который изучает расшифровку видеозаписи обыска \
(следственного действия) в Республике Казахстан.

Запись разбита по говорящим (SPEAKER_00, SPEAKER_01 и т.д.). Твоя задача — \
по содержанию реплик определить процессуальную роль каждого говорящего.

Возможные роли:
- следователь (ведёт обыск, представляется, разъясняет права, даёт команды, \
озвучивает ход записи)
- обыскиваемый (хозяин помещения / лицо, у которого проводится обыск)
- понятой (приглашённый свидетель, обычно молчит или подтверждает)
- адвокат (защитник)
- специалист (криминалист, переводчик и т.п.)
- иное (если роль не ясна)

ПРАВИЛА:
- Опирайся ТОЛЬКО на содержание реплик, не домысливай.
- Следователь обычно говорит первым, представляется, разъясняет права, \
озвучивает время и место (это сильные признаки).
- Если роль определить нельзя — поставь "иное" и низкую уверенность в reasoning.
- Не придумывай говорящих, которых нет в расшифровке.\
"""


def build_roles_prompt(protocol: str) -> str:
    """Пользовательский промпт прохода 1. На вход — начало протокола."""
    return f"""\
Ниже расшифровка начала видеозаписи обыска с таймкодами. \
Определи процессуальную роль каждого говорящего (SPEAKER_XX).

РАСШИФРОВКА:
{protocol}

Верни для каждого говорящего его метку (speaker), роль (role) и краткое \
обоснование (reasoning) на русском языке.\
"""


