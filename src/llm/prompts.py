from src.models.speech import DiarizationResult
from src.models.video import Timeline, EventType
from src.models.llm import Rule


# ---------------------------------------------------------------------------
# Проход 0: сборка "протокола с таймкодами" (без LLM)
# ---------------------------------------------------------------------------

def _fmt_ts(seconds: float) -> str:
    m, s = divmod(int(seconds), 60)
    return f"{m:02d}:{s:02d}"


def build_protocol(
    diarization: DiarizationResult,
    timeline: Timeline | None = None,
    roles: dict[str, str] | None = None,
) -> str:
    """
    Превращает диаризацию (+ опционально timeline) в компактный текстовый
    протокол с таймкодами — основной вход для LLM.

    Если передан roles (SPEAKER_XX → роль), подставляет роли вместо меток.
    Видео-события из timeline вставляются в общий поток по времени.

    Пример строки реплики:   [12:34] следователь: Откройте сейф.
    Пример строки события:    [14:02] «КАМЕРА ПЕРЕКРЫТА (coverage) 8.0с»
    """
    roles = roles or {}

    # Собираем единый поток (время, строка) из реплик и видео-событий
    rows: list[tuple[float, str]] = []

    for utt in diarization.utterances:
        speaker = roles.get(utt.speaker, utt.speaker)
        rows.append((utt.start, f"[{_fmt_ts(utt.start)}] {speaker}: {utt.text}"))

    if timeline is not None:
        for ev in timeline.events:
            # В протокол вставляем только видео-события, влияющие на оценку.
            # Смену спикера и тишину LLM и так видит по репликам.
            if ev.event_type in (EventType.OBSTRUCTION, EventType.PERSON_COUNT_CHANGE):
                rows.append((ev.timestamp, f"[{_fmt_ts(ev.timestamp)}] «{ev.description}»"))

    rows.sort(key=lambda r: r[0])
    return "\n".join(line for _, line in rows)


def format_rules(rules: list[Rule]) -> str:
    """Список правил в компактном виде для промпта (без severity — он не нужен модели)."""
    lines = []
    for r in rules:
        scope = {"audio": "по аудио", "video": "по видео",
                 "video+audio": "по аудио и видео"}.get(r.check, r.check)
        lines.append(f"[{r.rule_id}] ({scope}) {r.text}")
    return "\n".join(lines)


